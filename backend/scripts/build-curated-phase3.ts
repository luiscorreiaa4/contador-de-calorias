function normalizeKey(str: string): string {
  return str
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .trim();
}

function validateAndPush(
  food: CuratedOutputFood,
  phaseLabel: string,
  seenNames: Set<string>,
  seenIds: Set<string>,
  errors: string[],
  atwaterWarnings: string[],
  outputFoods: CuratedOutputFood[]
) {
  const normName = normalizeKey(food.name);
  if (seenNames.has(normName)) {
    errors.push(`[${phaseLabel}] Nome duplicado (normalizado): "${food.name}"`);
  }
  seenNames.add(normName);

  if (seenIds.has(food.external_id)) {
    errors.push(`[${phaseLabel}] external_id duplicado: "${food.external_id}"`);
  }
  seenIds.add(food.external_id);

  const atwater = 4 * food.proteins + 4 * food.carbs + 9 * food.fats;
  if (food.calories > 0) {
    const diff = Math.abs(atwater - food.calories) / food.calories;
    if (diff > 0.25) {
      atwaterWarnings.push(
        `[${phaseLabel}] Divergência Atwater > 25% em "${food.name}": inf=${food.calories} kcal vs calc=${Math.round(atwater)} kcal`
      );
    }
  } else if (atwater > 10) {
    atwaterWarnings.push(
      `[${phaseLabel}] Calorias = 0 mas macros somam ${Math.round(atwater)} kcal em "${food.name}"`
    );
  }

  if (food.calories < 0 || food.calories > 900) {
    errors.push(`[${phaseLabel}] Calorias fora do intervalo [0, 900] em "${food.name}": ${food.calories}`);
  }
  if (food.proteins + food.carbs + food.fats > 100.5) {
    errors.push(
      `[${phaseLabel}] Soma de macros > 100.5g em "${food.name}": ${(food.proteins + food.carbs + food.fats).toFixed(1)}g`
    );
  }
  if (food.unit_weight <= 0 || food.unit_weight > 1000) {
    errors.push(`[${phaseLabel}] Peso de unidade suspeito em "${food.name}": ${food.unit_weight}`);
  }

  outputFoods.push(food);
}

function runBuildPhase3() {
  const rootDir = process.cwd().endsWith('backend') ? process.cwd() : path.join(process.cwd(), 'backend');
  const tacoPath = path.join(rootDir, 'data/taco-full.json');
  const tbcaPath = path.join(rootDir, 'data/tbca-foods.json');

  if (!fs.existsSync(tacoPath)) {
    console.error(`Arquivo TACO não encontrado em ${tacoPath}`);
    process.exit(1);
  }
  if (!fs.existsSync(tbcaPath)) {
    console.error(`Arquivo TBCA não encontrado em ${tbcaPath}`);
    process.exit(1);
  }

  const tacoFoods: TacoItem[] = JSON.parse(fs.readFileSync(tacoPath, 'utf8'));
  const tacoMap = new Map<string, TacoItem>();
  for (const item of tacoFoods) {
    tacoMap.set(item.external_id, item);
  }

  const tbcaFoods: TbcaItem[] = JSON.parse(fs.readFileSync(tbcaPath, 'utf8'));
  const tbcaMap = new Map<string, TbcaItem>();
  for (const item of tbcaFoods) {
    tbcaMap.set(item.code, item);
  }

  console.log(`Carregados ${tacoFoods.length} alimentos da TACO e ${tbcaFoods.length} alimentos da TBCA.`);
  console.log(
    `Processando Fase 1 (${PHASE_1_MAPPINGS.length} itens) + Fase 2 (${PHASE_2_MAPPINGS.length} itens) + Fase 3 (${PHASE_3_LABEL_ITEMS.length} itens)...`
  );

  const outputFoods: CuratedOutputFood[] = [];
  const errors: string[] = [];
  const atwaterWarnings: string[] = [];
  const seenNames = new Set<string>();
  const seenIds = new Set<string>();

  // 1. Processar Fase 1 (TACO)
  for (const m of PHASE_1_MAPPINGS) {
    const src = tacoMap.get(m.tacoId);
    if (!src) {
      errors.push(`[Fase 1] ID TACO não encontrado: ${m.tacoId} para "${m.canonicalName}"`);
      continue;
    }

    const food: CuratedOutputFood = {
      name: m.canonicalName,
      calories: Math.round(src.calories),
      proteins: Math.round(src.proteins * 10) / 10,
      carbs: Math.round(src.carbs * 10) / 10,
      fats: Math.round(src.fats * 10) / 10,
      base_unit: m.baseUnit || 'g',
      serving_weight: 100,
      unit_name: m.unitName,
      unit_weight: m.unitWeight,
      source: 'TACO',
      source_ref: `TACO 4ª ed., código ${m.tacoId.replace('TACO-', '')} (${src.name})`,
      external_id: m.tacoId.toLowerCase(),
    };

    validateAndPush(food, 'Fase 1', seenNames, seenIds, errors, atwaterWarnings, outputFoods);
  }

  // 2. Processar Fase 2 (TBCA)
  for (const m of PHASE_2_MAPPINGS) {
    const src = tbcaMap.get(m.tbcaCode);
    if (!src) {
      errors.push(`[Fase 2] Código TBCA não encontrado no dataset: ${m.tbcaCode} para "${m.canonicalName}"`);
      continue;
    }

    const food: CuratedOutputFood = {
      name: m.canonicalName,
      calories: Math.round(src.calories),
      proteins: Math.round(src.proteins * 10) / 10,
      carbs: Math.round(src.carbs * 10) / 10,
      fats: Math.round(src.fats * 10) / 10,
      base_unit: m.baseUnit || 'g',
      serving_weight: 100,
      unit_name: m.unitName,
      unit_weight: m.unitWeight,
      source: 'TBCA',
      source_ref: `TBCA v7.2, código ${m.tbcaCode} (${src.sourceName})`,
      external_id: `tbca-${m.tbcaCode.toLowerCase()}`,
    };

    validateAndPush(food, 'Fase 2', seenNames, seenIds, errors, atwaterWarnings, outputFoods);
  }

  // 3. Processar Fase 3 (Rótulos e Fitness - conversão porção -> 100g/100ml)
  for (const item of PHASE_3_LABEL_ITEMS) {
    const factor = 100 / item.portionWeight;
    const calories = Math.round(item.portionCalories * factor);
    const proteins = Math.round(item.portionProteins * factor * 10) / 10;
    const carbs = Math.round(item.portionCarbs * factor * 10) / 10;
    const fats = Math.round(item.portionFats * factor * 10) / 10;

    const food: CuratedOutputFood = {
      name: item.canonicalName,
      calories,
      proteins,
      carbs,
      fats,
      base_unit: item.baseUnit || 'g',
      serving_weight: 100,
      unit_name: item.unitName,
      unit_weight: item.unitWeight,
      source: item.brand,
      source_ref: item.labelDescription,
      external_id: item.externalId,
    };

    validateAndPush(food, 'Fase 3', seenNames, seenIds, errors, atwaterWarnings, outputFoods);
  }

  console.log(`\nRelatório de Validação da Curadoria Completa (Fases 1, 2 e 3):`);
  console.log(`- Alimentos da Fase 1 (TACO): ${PHASE_1_MAPPINGS.length}`);
  console.log(`- Alimentos da Fase 2 (TBCA): ${PHASE_2_MAPPINGS.length}`);
  console.log(`- Alimentos da Fase 3 (Rótulos / Fitness): ${PHASE_3_LABEL_ITEMS.length}`);
  console.log(`- Total Geral Curado: ${outputFoods.length}`);
  console.log(`- Erros críticos: ${errors.length}`);

  if (errors.length > 0) {
    errors.forEach((e) => console.error('  * ERRO:', e));
    process.exit(1);
  }

  console.log(`- Alertas de conferência Atwater (>25%): ${atwaterWarnings.length}`);
  atwaterWarnings.forEach((w) => console.warn('  ! AVISO:', w));

  const targetPath = path.join(rootDir, 'data/curated-foods.json');
  fs.writeFileSync(targetPath, JSON.stringify(outputFoods, null, 2), 'utf8');
  console.log(`\n✅ Base curada completa (Fases 1 + 2 + 3) gerada com sucesso em: ${targetPath}`);
}

runBuildPhase3();

